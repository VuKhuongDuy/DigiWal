#!/usr/bin/env bash
# Write hsm-gateway's pinned-callers file (key-custody-hsm.md invariant 25, K15): for each service name given, the
# SHA-256 of its CURRENT leaf certificate (infra/pki/out/<name>/cert.pem), under CN <name>.
#   infra/pki/gen-callers.sh <out-file> wallet-service [sweep-signer ...]
# Run it wherever the leaves are (vm2 holds the CA and every leaf), then restart hsm-gateway. Re-issuing a leaf
# (gen-leaf.sh) changes its fingerprint, so re-run this and restart the gateway: a stale pin refuses the caller,
# which is the point.
set -euo pipefail

if [[ $# -lt 2 ]]; then
  echo "usage: $0 <out-file> <service-name>..." >&2
  exit 2
fi
OUT="$1"; shift
HERE="$(cd "$(dirname "$0")" && pwd)"

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
{
  echo "# Generated by infra/pki/gen-callers.sh: SHA-256 of each pinned caller's leaf certificate (DER)."
  echo "callers:"
  for svc in "$@"; do
    cert="$HERE/out/$svc/cert.pem"
    [[ -f "$cert" ]] || { echo "no leaf for $svc ($cert): run infra/pki/gen-leaf.sh $svc" >&2; exit 1; }
    fp="$(openssl x509 -in "$cert" -outform DER | openssl dgst -sha256 -r | awk '{print $1}')"
    [[ "$fp" =~ ^[0-9a-f]{64}$ ]] || { echo "could not fingerprint $cert" >&2; exit 1; }
    echo "  - cn: $svc"
    echo "    sha256: \"$fp\""
  done
} > "$tmp"
mkdir -p "$(dirname "$OUT")"
install -m 644 "$tmp" "$OUT"
echo "wrote $OUT ($# caller(s))"
