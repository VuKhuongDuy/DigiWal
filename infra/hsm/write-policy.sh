#!/usr/bin/env bash
# Write the Signing Policy for the DEV / e2e hsm-gateway from the address init-token printed.
#   infra/hsm/write-policy.sh <config-dir> <hot_address> [chain_id]
# Warm address comes from infra/treasury.yaml (the chain's entry), the ERC-20 test token is the e2e asset registry's
# (the address Anvil gives account #0's first contract). Caps follow the scale of infra/assets.yaml (hot_floor 30 ETH,
# hot_ceiling 120 ETH): window_1h = floor/3, window_24h = ceiling. Edit the file and restart the gateway to change them.
set -euo pipefail
DIR="${1:?usage: write-policy.sh <config-dir> <hot_address> [chain_id]}"
HOT="${2:?hot address}"
CHAIN="${3:-31337}"
HERE="$(cd "$(dirname "$0")" && pwd)"
[[ "$HOT" =~ ^0x[0-9a-fA-F]{40}$ ]] || { echo "not an address: $HOT" >&2; exit 2; }

WARM="$(awk -v c="$CHAIN" '$1=="-" && $2=="chain_id:" {on=($3==c)} on && $1=="warm_address:" {gsub(/"/,"",$2); print $2; exit}' "$HERE/../treasury.yaml")"
[[ "$WARM" =~ ^0x[0-9a-fA-F]{40}$ ]] || { echo "no warm_address for chain $CHAIN in infra/treasury.yaml" >&2; exit 1; }
TOKEN="$(awk '$1=="contract_address:" {gsub(/"/,"",$2); print $2; exit}' "$HERE/../../e2e/assets.yaml")"

umask 022
cat > "$DIR/policy.yaml" <<POLICY
# Signing Policy for the dev / e2e hsm-gateway (generated by infra/hsm/write-policy.sh; see
# services/hsm-gateway/config/policy.example.yaml for every field).
enabled: true
chain_id: $CHAIN
hot_address: "$HOT"
warm_address: "$WARM"
denied_recipients: []
native:
  max_per_tx: "5000000000000000000"
  treasury_max_per_tx: "120000000000000000000"
  window_1h: "10000000000000000000"
  window_24h: "120000000000000000000"
tokens:
  - symbol: TT
    contract: "$TOKEN"
    max_per_tx: "1000000000000000000000"
    treasury_max_per_tx: "4000000000000000000000"
    window_1h: "333000000000000000000"
    window_24h: "4000000000000000000000"
POLICY
echo "wrote $DIR/policy.yaml (hot $HOT, warm $WARM, chain $CHAIN)"
